import {
  assignmentResults,
  deleteAssignment,
  getResult,
  getStudentCopy,
  listAssignments,
  putAssignment,
  readPayload,
  startAttempt,
  submitAttempt,
} from "./assignments";
import { clearSessionCookie, isTeacher, makeSession, safeEqual, sessionCookie } from "./auth";
import { libraryPage, loginPage, PAGE_CSP, resultsListPage, resultsPage, type LessonEntry } from "./pages";
import { createB2Store, type FileStore } from "./storage";

export type AppEnv = Env & { B2_KEY_ID: string; B2_APP_KEY: string; TEACHER_PASSWORD: string };

const ASSET_NAME = /^[A-Za-z0-9._-]{1,128}$/;
const LESSON_ID = /^[A-Za-z0-9_-]{1,64}$/;
const MAX_ASSET_BYTES = 25 * 1024 * 1024;
const MAX_LESSON_BYTES = 5 * 1024 * 1024;
const INDEX_KEY = "lessons/index.json";

/** Only pictures and sounds: no SVG, since a served SVG can carry script. */
const ASSET_TYPES: Record<string, string> = {
  png: "image/png",
  jpg: "image/jpeg",
  jpeg: "image/jpeg",
  webp: "image/webp",
  gif: "image/gif",
  mp3: "audio/mpeg",
  m4a: "audio/mp4",
  aac: "audio/aac",
  ogg: "audio/ogg",
  wav: "audio/wav",
};

/** The lesson page is generated by the app and needs inline script; nothing else may load. */
const LESSON_CSP = "default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src 'self' data: blob:; media-src 'self' data: blob:; font-src data:; base-uri 'none'; form-action 'none'";

/** The students' page is the app's own build (static files under /student/), talking only to this server. */
const STUDENT_CSP =
  "default-src 'none'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; media-src 'self' data: blob:; font-src 'self' data:; connect-src 'self'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'";

/** A short Chinese title, shown large on the lesson's card. */
const HANZI = /^\p{Script=Han}{1,6}$/u;

const json = (data: unknown, status = 200) => Response.json(data, { status, headers: { "Cache-Control": "no-store" } });
const text = (message: string, status: number) => new Response(message, { status, headers: { "Cache-Control": "no-store" } });

function html(body: string, status = 200): Response {
  return new Response(body, {
    status,
    headers: { "Content-Type": "text/html; charset=utf-8", "Cache-Control": "no-store", "Content-Security-Policy": PAGE_CSP, "X-Robots-Tag": "noindex" },
  });
}

async function readIndex(store: FileStore): Promise<LessonEntry[]> {
  const res = await store.get(INDEX_KEY);
  if (!res.ok) return [];
  try {
    const data: unknown = await res.json();
    return Array.isArray(data) ? (data as LessonEntry[]) : [];
  } catch {
    return [];
  }
}

const writeIndex = (store: FileStore, entries: LessonEntry[]) => store.put(INDEX_KEY, JSON.stringify(entries), "application/json");

async function serveAsset(request: Request, ctx: ExecutionContext, store: FileStore, name: string): Promise<Response> {
  const type = ASSET_TYPES[name.split(".").pop()?.toLowerCase() ?? ""];
  if (!ASSET_NAME.test(name) || !type) return text("Not found", 404);

  // The Cache API only works on a custom domain; elsewhere match() finds nothing
  // and every request falls through to B2.
  const cache = caches.default;
  const cacheKey = new Request(new URL(`/f/${name}`, request.url).toString());
  const range = request.headers.get("Range");
  const cached = await cache.match(range ? new Request(cacheKey, { headers: { Range: range } }) : cacheKey);
  if (cached) return cached;

  const upstream = await store.get(`assets/${name}`, range);
  if (!upstream.ok) {
    if (upstream.status !== 404) console.error(`B2 get assets/${name}: ${upstream.status} ${(await upstream.text()).slice(0, 300)}`);
    return text("Not found", upstream.status === 404 ? 404 : 502);
  }

  const headers = new Headers({
    "Content-Type": type,
    "Cache-Control": "public, max-age=31536000, immutable",
    "Accept-Ranges": "bytes",
    "X-Content-Type-Options": "nosniff",
  });
  for (const h of ["Content-Length", "Content-Range", "ETag"]) {
    const v = upstream.headers.get(h);
    if (v) headers.set(h, v);
  }
  // Fill the cache with the whole file so later Range requests are answered from it.
  ctx.waitUntil(
    (async () => {
      const full = range ? await store.get(`assets/${name}`) : upstream.clone();
      if (!full.ok) return;
      await cache.put(cacheKey, new Response(full.body, { headers: { "Content-Type": type, "Cache-Control": headers.get("Cache-Control")! } }));
    })(),
  );
  return new Response(upstream.body, { status: upstream.status, headers });
}

async function handle(request: Request, env: AppEnv, ctx: ExecutionContext): Promise<Response> {
  const url = new URL(request.url);
  const { pathname } = url;
  const method = request.method;
  const store = createB2Store(env);

  if (pathname === "/robots.txt") return text("User-agent: *\nDisallow: /\n", 200);

  const asset = /^\/f\/([^/]+)$/.exec(pathname);
  if (asset && (method === "GET" || method === "HEAD")) return serveAsset(request, ctx, store, asset[1]!);

  // Students: open to anyone holding an exercise's link.
  const studentPage = /^\/a\/([a-z0-9]{12})$/.exec(pathname);
  if (studentPage && method === "GET") {
    const shell = await env.ASSETS.fetch(new Request(new URL("/student/student.html", request.url)));
    if (!shell.ok) return text("Not found", 404);
    return new Response(shell.body, {
      headers: {
        "Content-Type": "text/html; charset=utf-8",
        "Cache-Control": "no-store",
        "Content-Security-Policy": STUDENT_CSP,
        "X-Robots-Tag": "noindex",
        "Referrer-Policy": "no-referrer",
      },
    });
  }
  const studentApi = /^\/api\/a\/([a-z0-9]{12})(?:\/(start|submit)|\/result\/([a-z0-9_]+))?$/.exec(pathname);
  if (studentApi) {
    const slug = studentApi[1]!;
    const action = studentApi[2];
    const attemptId = studentApi[3];
    if (!action && !attemptId && method === "GET") return getStudentCopy(env.DB, slug, url);
    if (action === "start" && method === "POST") return startAttempt(env.DB, slug, request);
    if (action === "submit" && method === "POST") return submitAttempt(env.DB, slug, request);
    if (attemptId && method === "GET") return getResult(env.DB, slug, attemptId);
    return json({ error: "not-found" }, 404);
  }

  if (pathname === "/login") {
    if (method === "GET") return html(loginPage());
    if (method === "POST") {
      const password = String((await request.formData()).get("password") ?? "");
      if (!safeEqual(password, env.TEACHER_PASSWORD)) return html(loginPage("Sai mật khẩu."), 401);
      return new Response(null, { status: 303, headers: { Location: "/", "Set-Cookie": sessionCookie(await makeSession(env.TEACHER_PASSWORD)) } });
    }
  }

  if (pathname === "/logout" && method === "POST") {
    return new Response(null, { status: 303, headers: { Location: "/login", "Set-Cookie": clearSessionCookie() } });
  }

  // Everything below is for the teacher.
  if (!(await isTeacher(request, env.TEACHER_PASSWORD))) {
    return pathname.startsWith("/api/") ? json({ error: "unauthorized" }, 401) : new Response(null, { status: 303, headers: { Location: "/login" } });
  }

  if (pathname === "/" && method === "GET") return html(libraryPage(await readIndex(store)));

  if (pathname === "/results" && method === "GET") {
    const rows = await listAssignments(env.DB);
    return html(
      resultsListPage(
        rows.map((r) => ({
          id: r.id,
          slug: r.slug,
          title: r.title,
          lessonTitle: r.lesson_title,
          submitted: r.submitted,
          students: r.students,
          avgPercent: r.avg_percent,
          lastSubmitted: r.last_submitted,
        })),
      ),
    );
  }
  const results = /^\/results\/([^/]+)$/.exec(pathname);
  if (results && method === "GET") {
    const found = await assignmentResults(env.DB, results[1]!);
    if (!found) return text("Not found", 404);
    const { settings } = readPayload(found.assignment).exercise;
    return html(
      resultsPage(
        {
          slug: found.assignment.slug,
          title: found.assignment.title,
          lessonTitle: found.assignment.lesson_title,
          timeLimit: settings.timeLimit,
          passPercent: settings.passPercent,
          inProgress: found.inProgress,
        },
        found.attempts.map((a) => ({
          name: a.student_name,
          clientId: a.client_id,
          score: a.score ?? 0,
          max: a.max_score ?? 0,
          percent: a.percent ?? 0,
          startedAt: a.started_at,
          submittedAt: a.submitted_at!,
        })),
      ),
    );
  }

  const assignment = /^\/api\/assignments\/([^/]+)$/.exec(pathname);
  if (assignment && method === "PUT") return putAssignment(env.DB, assignment[1]!, request);
  if (assignment && method === "DELETE") return deleteAssignment(env.DB, assignment[1]!);

  const lesson = /^\/l\/([^/]+)$/.exec(pathname);
  if (lesson && method === "GET") {
    if (!LESSON_ID.test(lesson[1]!)) return text("Not found", 404);
    const res = await store.get(`lessons/${lesson[1]}.html`);
    if (!res.ok) return text("Not found", res.status === 404 ? 404 : 502);
    return new Response(res.body, {
      headers: { "Content-Type": "text/html; charset=utf-8", "Cache-Control": "private, no-store", "Content-Security-Policy": LESSON_CSP, "X-Robots-Tag": "noindex" },
    });
  }

  // The app names files by content hash, so a name already stored needs no upload.
  if (pathname === "/api/assets/missing" && method === "POST") {
    const body: unknown = await request.json().catch(() => null);
    const names = (body as { names?: unknown } | null)?.names;
    if (!Array.isArray(names) || names.length > 500 || !names.every((n) => typeof n === "string" && ASSET_NAME.test(n))) {
      return json({ error: "bad-names" }, 400);
    }
    const missing: string[] = [];
    // A few at a time, so a big lesson does not fire dozens of B2 requests at once.
    for (let i = 0; i < names.length; i += 8) {
      const batch = names.slice(i, i + 8);
      const found = await Promise.all(batch.map((n) => store.exists(`assets/${n}`)));
      missing.push(...batch.filter((_, j) => !found[j]));
    }
    return json({ missing });
  }

  const putAsset = /^\/api\/assets\/([^/]+)$/.exec(pathname);
  if (putAsset && method === "PUT") {
    const name = putAsset[1]!;
    const type = ASSET_TYPES[name.split(".").pop()?.toLowerCase() ?? ""];
    if (!ASSET_NAME.test(name) || !type) return json({ error: "bad-name" }, 400);
    const body = await request.arrayBuffer();
    if (body.byteLength > MAX_ASSET_BYTES) return json({ error: "too-large" }, 413);
    await store.put(`assets/${name}`, body, type);
    return json({ ok: true, url: `/f/${name}` });
  }

  const putLesson = /^\/api\/lessons\/([^/]+)$/.exec(pathname);
  if (putLesson) {
    const id = putLesson[1]!;
    if (!LESSON_ID.test(id)) return json({ error: "bad-id" }, 400);
    if (method === "PUT") {
      const body = await request.text();
      if (body.length > MAX_LESSON_BYTES) return json({ error: "too-large" }, 413);
      const title = (url.searchParams.get("title") ?? id).slice(0, 200);
      const hanzi = url.searchParams.get("hanzi")?.trim() ?? "";
      await store.put(`lessons/${id}.html`, body, "text/html; charset=utf-8");
      const entries = (await readIndex(store)).filter((e) => e.id !== id);
      entries.push({ id, title, ...(HANZI.test(hanzi) ? { hanzi } : {}), updatedAt: new Date().toISOString() });
      await writeIndex(store, entries);
      return json({ ok: true, url: `/l/${id}` });
    }
    if (method === "DELETE") {
      await store.delete(`lessons/${id}.html`);
      await writeIndex(store, (await readIndex(store)).filter((e) => e.id !== id));
      return json({ ok: true });
    }
  }

  return text("Not found", 404);
}

export default {
  async fetch(request, env, ctx) {
    try {
      return await handle(request, env as AppEnv, ctx);
    } catch (e) {
      console.error(`${request.method} ${new URL(request.url).pathname}:`, e instanceof Error ? e.message : e);
      return text("Internal error", 500);
    }
  },
} satisfies ExportedHandler<Env>;
